def apply_rewrites(csv_path: Path, slugs: list[str]) -> int:
    rows = list(csv.DictReader(csv_path.open(encoding="utf-8-sig")))
    fieldnames = rows[0].keys()
    n = 0
    for row in rows:
        slug = row.get("slug", "")
        if slug not in slugs:
            continue
        patch = REWRITES[slug]
        row["revision_note"] = REVISION
        row["fact_checked_at"] = TODAY
        row["last_reviewed_at"] = TODAY
        row["source_checked_at"] = TODAY
        row["original_note"] = f"手書きリライト {TODAY}。"
        for k, v in patch.items():
            row[k] = v
        n += 1
    with csv_path.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames, lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    return n


def main() -> int:
    root = Path(__file__).resolve().parents[1]
    csv_path = root / "data" / "guide_articles.csv"
    slugs = list(REWRITES.keys())
    n = apply_rewrites(csv_path, slugs)
    print(f"patched {n} rows: {', '.join(slugs)}")
    return 0


