def patch_csv(path: Path, key_col: str, fixes: dict) -> None:
    with path.open(encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))
        fieldnames = rows[0].keys() if rows else []

    for row in rows:
        title = row.get("title", "").strip()
        if title not in fixes:
            continue
        fix = fixes[title]
        if "slug" in fix:
            row["slug"] = fix["slug"]
        if "related_terms" in fix:
            row["related_terms"] = fix["related_terms"]
        if "faqs" in fix:
            for i, (q, a) in enumerate(fix["faqs"], start=1):
                row[f"faq_{i}_question"] = q
                row[f"faq_{i}_answer"] = a

    with path.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames, lineterminator="\n")
        w.writeheader()
        w.writerows(rows)


def main() -> None:
    patch_csv(DATA / "numbers.csv", "title", NUMBERS_FIXES)
    patch_csv(DATA / "mistakes.csv", "title", MISTAKE_FIXES)
    print("patched numbers.csv and mistakes.csv")


if __name__ == "__main__":
    main()
