def _ensure_hub_row(row: dict) -> dict:
    row = dict(row)
    if len(row.get("common_mistakes", "")) < 15:
        row["common_mistakes"] = (
            row.get("common_mistakes", "") + "（試験では条件文の主語確認が得点の分かれ目）"
        )
    if len(row.get("memory_tip", "")) < 10:
        row["memory_tip"] = row.get("memory_tip", "") + "・条文で確認"
    if row.get("exam_points", "").count(";") < 1:
        row["exam_points"] = row.get("exam_points", "") + ";条件文の主語を確認"
    if len(row.get("article_title", "")) < 10:
        row["article_title"] = row["article_title"] + "（試験対策）"
    if len(row.get("highlight", "")) < 3:
        row["highlight"] = (row.get("highlight", "") + "・要項確認") or "要項確認"
    for n in range(1, 5):
        q = row.get(f"faq_{n}_question", "")
        if q and len(q) < 6:
            row[f"faq_{n}_question"] = (q[:-1] + "ですか？" if q.endswith("？") else q + "ですか？")
    return row


